-- Period code for humans and ad-hoc SQL. The engine renders periods in Rust
-- (lanka-core period.rs, which also knows the profile's seasons and fiscal
-- start); this covers the frequencies that need no profile.
CREATE FUNCTION data.period_code(f "char", d date) RETURNS text
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT CASE f
    WHEN 'A' THEN to_char(d, 'YYYY')
    WHEN 'F' THEN to_char(d, 'YYYY') || '/' || to_char(d + interval '1 year', 'YY')
    WHEN 'H' THEN to_char(d, 'YYYY') || '-H' || CASE WHEN extract(month FROM d) < 7 THEN '1' ELSE '2' END
    WHEN 'Q' THEN to_char(d, 'YYYY') || '-Q' || to_char(d, 'Q')
    WHEN 'M' THEN to_char(d, 'YYYY-MM')
    WHEN 'W' THEN to_char(d, 'IYYY') || '-W' || to_char(d, 'IW')
    WHEN 'D' THEN to_char(d, 'YYYY-MM-DD')
    WHEN 'P' THEN CASE WHEN to_char(d, 'MM-DD') = '01-01' THEN to_char(d, 'YYYY') ELSE to_char(d, 'YYYY-MM-DD') END
    ELSE to_char(d, 'YYYY-MM-DD') END
$$;

