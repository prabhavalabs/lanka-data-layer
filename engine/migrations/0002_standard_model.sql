-- The only UPDATE observations ever see is the vto close at release.
CREATE FUNCTION data.observations_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.obs_id, NEW.value, NEW.lo, NEW.hi, NEW.dataset_key, NEW.indicator_key, NEW.geo_key,
      NEW.dims_key, NEW.vfrom, NEW.flags, NEW.time_start, NEW.geo_level, NEW.basis, NEW.status, NEW.freq)
     IS DISTINCT FROM
     (OLD.obs_id, OLD.value, OLD.lo, OLD.hi, OLD.dataset_key, OLD.indicator_key, OLD.geo_key,
      OLD.dims_key, OLD.vfrom, OLD.flags, OLD.time_start, OLD.geo_level, OLD.basis, OLD.status, OLD.freq)
  THEN
    RAISE EXCEPTION 'data.observations rows are immutable except vto (obs_id %)', OLD.obs_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER observations_guard BEFORE UPDATE ON data.observations
  FOR EACH ROW EXECUTE FUNCTION data.observations_guard();

-- One partition per dataset (+ its provenance partition), with the indexes
-- of 05 §2.3. Called at registry sync; idempotent.
CREATE OR REPLACE FUNCTION data.ensure_obs_partition(p_dataset text)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  k    int4;
  part text;
  prov text;
BEGIN
  SELECT key INTO k FROM catalog.datasets WHERE id = p_dataset;
  IF k IS NULL THEN
    RAISE EXCEPTION 'ensure_obs_partition: unknown dataset %', p_dataset;
  END IF;
  part := 'observations_' || k;
  prov := 'obs_provenance_' || k;
  IF to_regclass('data.' || part) IS NULL THEN
    EXECUTE format('CREATE TABLE data.%I PARTITION OF data.observations FOR VALUES IN (%s)
                    WITH (fillfactor = 100, autovacuum_vacuum_scale_factor = 0.02,
                          autovacuum_vacuum_insert_scale_factor = 0.1)', part, k);
    -- series for <= 25 geographies: index-only
    EXECUTE format('CREATE INDEX %I ON data.%I (indicator_key, geo_key, dims_key, time_start)
                    INCLUDE (value, lo, hi, basis, status, flags, freq, obs_id, vfrom)
                    WHERE vto = 2147483647', part || '_series', part);
    -- choropleth: one index-only range scan per level
    EXECUTE format('CREATE INDEX %I ON data.%I (indicator_key, time_start, freq, geo_level, dims_key)
                    INCLUDE (geo_key, value, lo, hi, basis, status, flags, obs_id, vfrom)
                    WHERE vto = 2147483647', part || '_map', part);
    -- provenance / history lookup by id (ids are assigned in insert order)
    EXECUTE format('CREATE INDEX %I ON data.%I USING brin (obs_id) WITH (pages_per_range = 16)',
                   part || '_obs', part);
    EXECUTE format('COMMENT ON TABLE data.%I IS %L', part, 'observations of dataset ' || p_dataset);
  END IF;
  IF to_regclass('data.' || prov) IS NULL THEN
    EXECUTE format('CREATE TABLE data.%I PARTITION OF data.obs_provenance FOR VALUES IN (%s)', prov, k);
  END IF;
  RETURN part;
END $$;

DO $$ BEGIN PERFORM data.ensure_obs_partition(id) FROM catalog.datasets ORDER BY key; END $$;

