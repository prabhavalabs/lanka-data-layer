CREATE TEMP TABLE obs_map ON COMMIT DROP AS
  SELECT o.obs_id AS old_obs_id, o.value, o.status::text AS old_status, o.period_start,
         o.artifact_id, o.locator, o.verbatim, o.method::text AS method, o.confidence,
         o.review::text AS review, o.version_id,
         d.key AS dataset_key, i.key AS indicator_key, i.freq, u.key AS geo_key, u.level AS geo_level,
         ds.key AS dims_key, v.seq, v.status AS vstatus, (cv.version_id IS NOT DISTINCT FROM v.id) AS is_current,
         (d.key::int8 << 40) | row_number() OVER (PARTITION BY d.key ORDER BY o.obs_id) AS obs_id
  FROM data.observations_0001 o
  JOIN catalog.datasets d ON d.id = o.dataset_id
  JOIN catalog.indicators i ON i.id = o.indicator_id
  JOIN geo.units u ON u.code = o.geo_code
  JOIN catalog.dim_sets ds ON ds.dims = o.dims
  JOIN data.dataset_versions v ON v.id = o.version_id
  LEFT JOIN data.current_versions cv ON cv.dataset_id = o.dataset_id
  WHERE v.status NOT IN ('rejected', 'withdrawn');

INSERT INTO data.observations (obs_id, value, lo, hi, dataset_key, indicator_key, geo_key, dims_key,
                               vfrom, vto, flags, time_start, geo_level, basis, status, freq)
  SELECT obs_id, value, NULL, NULL, dataset_key, indicator_key, geo_key, dims_key, seq,
         CASE WHEN is_current OR vstatus IN ('staged', 'in_review', 'approved') THEN 2147483647 ELSE seq END,
         0, period_start, geo_level,
         CASE old_status WHEN 'estimate' THEN 3 WHEN 'modelled' THEN 3 WHEN 'forecast' THEN 4
                         WHEN 'derived' THEN 2 ELSE 1 END,
         CASE old_status WHEN 'revised' THEN 3 WHEN 'provisional' THEN 2 WHEN 'not_available' THEN 6
                         WHEN 'nil' THEN 7 WHEN 'suppressed' THEN 8 ELSE 1 END,
         freq
  FROM obs_map;

INSERT INTO data.obs_provenance (obs_id, dataset_key, artifact_id, locator, verbatim, method,
                                 confidence, review)
  SELECT obs_id, dataset_key, artifact_id, coalesce(locator, '{}'), verbatim,
         (SELECT code FROM data.code_labels WHERE codelist = 'method' AND label = m.method),
         confidence,
         (SELECT code FROM data.code_labels WHERE codelist = 'review' AND label = m.review)
  FROM obs_map m WHERE artifact_id IS NOT NULL;

-- An open (staged/in-review) 0001 version was a full copy: releasing it
-- closes every row of the current version.
INSERT INTO data.version_closes (version_id, obs_id)
  SELECT ov.id, c.obs_id
  FROM data.dataset_versions ov
  JOIN catalog.datasets d ON d.id = ov.dataset_id
  JOIN data.current_versions cv ON cv.dataset_id = ov.dataset_id
  JOIN obs_map c ON c.dataset_key = d.key AND c.version_id = cv.version_id
  WHERE ov.status IN ('staged', 'in_review', 'approved');

UPDATE catalog.datasets d SET obs_seq = m.n
  FROM (SELECT dataset_key, count(*) AS n FROM obs_map GROUP BY 1) m
  WHERE m.dataset_key = d.key;

-- Parity: every copied row exists with the identical value, and nothing was
-- dropped except rows of rejected/withdrawn versions.
DO $$
DECLARE
  expected bigint;
  copied   bigint;
  bad      bigint;
BEGIN
  SELECT count(*) INTO expected FROM data.observations_0001 o
    JOIN data.dataset_versions v ON v.id = o.version_id WHERE v.status NOT IN ('rejected', 'withdrawn');
  SELECT count(*) INTO copied FROM data.observations;
  IF copied <> expected THEN
    RAISE EXCEPTION 'migration 0002 parity: % of % observations copied (unresolved geo/indicator/dims?)',
      copied, expected;
  END IF;
  SELECT count(*) INTO bad FROM obs_map m
    LEFT JOIN data.observations n ON n.dataset_key = m.dataset_key AND n.obs_id = m.obs_id
    WHERE n.obs_id IS NULL OR n.value IS DISTINCT FROM m.value OR n.time_start <> m.period_start;
  IF bad > 0 THEN
    RAISE EXCEPTION 'migration 0002 parity: % rows differ after copy', bad;
  END IF;
  SELECT count(*) INTO bad FROM obs_map m WHERE m.artifact_id IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM data.obs_provenance p
                    WHERE p.dataset_key = m.dataset_key AND p.obs_id = m.obs_id
                      AND p.locator = coalesce(m.locator, '{}') AND p.verbatim IS NOT DISTINCT FROM m.verbatim);
  IF bad > 0 THEN
    RAISE EXCEPTION 'migration 0002 parity: % provenance rows differ after copy', bad;
  END IF;
END $$;

