-- Lanka Data Layer v2 — the standard model (WP-01).
-- Design: docs/architecture-v2/02-standard-model.md, 05-storage-and-performance.md §1–§3,
-- ADRs 0004–0007. Runs in one transaction (sqlx default). The only destructive
-- migration: data.observations is rebuilt (integer keys, version ranges,
-- basis/status/flags, lo/hi, provenance in a side table) and geo.admin_units
-- becomes a view over geo.units + geo.unit_geoms. Row-level parity of the
-- copied observations is asserted at the end of this file.
--
-- Not done here (by design): multiset/schema hashes and the new dsvs need the
-- canonical row encoding (ryu floats, canonical JSON) and are backfilled by
-- the engine (`lanka db migrate` → registry sync → hash backfill); until then
-- a version keeps its 0001 dsv, which is also copied to legacy_dsv.

